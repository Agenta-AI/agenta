// Writes theme.css, theme.tailwind.css, tokens.json and the DESIGN.md tables from theme.config.ts,
// and rules.json (the principles and rules) from DESIGN.md for the guide.
import {existsSync, readFileSync, writeFileSync} from "fs"
import {dirname, resolve} from "path"
import {fileURLToPath} from "url"

import {
    breakpoints,
    colorAliases,
    colors,
    durations,
    easings,
    fontFamilies,
    radius,
    shadows,
    sizes,
    spacing,
    textStyles,
    zIndex,
    type ThemeMode,
    type ThemeVariable,
} from "../src/design/theme.config"

const HERE = dirname(fileURLToPath(import.meta.url))
const DESIGN = resolve(HERE, "../src/design")
const DESIGN_MD = resolve(HERE, "../DESIGN.md")

// Light on :root; dark on the `.dark` class that _document.tsx sets on <html> before paint.
const SCOPE = ":root"
const DARK_SCOPE = ".dark"

const HEADER = "/* GENERATED by scripts/generate-theme.ts from src/design/theme.config.ts. Do not edit. */"
// A compact window (below breakpoint-sm) steps the default and large controls down one size.
const COMPACT_SIZES = ["control-md", "control-lg"]

const cssName = (name: string) => `--${name.replace(/\\/g, "\\\\").replace(/\./g, "\\.")}`

function block(selector: string, lines: string[]) {
    return `${selector} {\n${lines.map((l) => `    ${l}`).join("\n")}\n}`
}

function themeCss(): string {
    const plain = (list: ThemeVariable[]) => list.map((v) => `${cssName(v.name)}: ${v.value};`)
    const light = [
        ...colors.map((c) => `--${c.name}: ${c.value.light};`),
        ...shadows.map((s) => `--${s.name}: ${s.value.light};`),
        ...Object.entries(fontFamilies).map(([k, v]) => `--font-${k}: ${v};`),
        ...textStyles.flatMap((t) => [
            `--${t.name}: ${t.fontSize};`,
            `--${t.name}--line-height: ${t.lineHeight};`,
            `--${t.name}--font-weight: ${t.fontWeight};`,
            `--${t.name}--letter-spacing: ${t.letterSpacing ?? "0"};`,
        ]),
        ...plain(spacing),
        ...plain(radius),
        ...plain(sizes),
        ...plain(durations),
        ...plain(easings),
        ...plain(breakpoints),
        ...plain(zIndex),
    ]
    const dark = [
        ...colors.map((c) => `--${c.name}: ${c.value.dark};`),
        ...shadows.map((s) => `--${s.name}: ${s.value.dark};`),
        "color-scheme: dark;",
    ]
    const compact = COMPACT_SIZES.map((n) => `--${n}: var(--${n}-compact);`)
    return [
        HEADER,
        block(SCOPE, light),
        block(DARK_SCOPE, dark),
        `/* Small screens get smaller controls: the default and large sizes step down one size. Touch never grows a control's look. */\n@media (max-width: 639px) {\n${block(`    ${SCOPE}`, compact).replace(/\n/g, "\n    ")}\n}`,
        "",
    ].join("\n\n")
}

// No `--<namespace>-*: initial` resets: stock keys (text-xs, md:, shadow-sm, gray-500, ...) are still
// in use. Add the resets once design:ratchet shows those uses at zero.
function tailwindCss(): string {
    const lines = [
        ...colors.map((c) => `--color-${c.name}: var(--${c.name});`),
        ...Object.entries(colorAliases).map(([alias, to]) => `--color-${alias}: var(--${to});`),
        ...Object.keys(fontFamilies).map((k) => `--font-${k}: var(--font-${k});`),
        ...textStyles.flatMap((t) => [
            `--text-${t.name.replace(/^text-/, "")}: var(--${t.name});`,
            `--text-${t.name.replace(/^text-/, "")}--line-height: var(--${t.name}--line-height);`,
            `--text-${t.name.replace(/^text-/, "")}--font-weight: var(--${t.name}--font-weight);`,
            `--text-${t.name.replace(/^text-/, "")}--letter-spacing: var(--${t.name}--letter-spacing);`,
        ]),
        "--spacing: 4px;",
        ...radius.map((r) => `--${r.name}: var(--${r.name});`),
        ...shadows.map((s) => `--${s.name}: var(--${s.name});`),
        ...breakpoints.map((b) => `--${b.name}: ${b.value};`),
        // max-w-content-sm / -md / -lg (LAYOUT-02).
        ...sizes.filter((s) => s.name.startsWith("content-")).map((s) => `--container-${s.name}: var(--${s.name});`),
        // w-popover-sm / -md / -lg and h-row-dense / -single / -double.
        ...sizes.filter((s) => s.name.startsWith("popover-")).map((s) => `--container-${s.name}: var(--${s.name});`),
        ...sizes.filter((s) => s.name.startsWith("row-")).map((s) => `--spacing-${s.name}: var(--${s.name});`),
        ...easings.map((e) => `--${e.name}: var(--${e.name});`),
    ]
    // Tailwind's --text-* theme keys cannot carry a font family, so mono styles add it here.
    const monoUtilities = textStyles
        .filter((t) => t.family === "mono")
        .map((t) => block(`@utility ${t.name}`, ["font-family: var(--font-mono);"]))
    return [
        HEADER,
        "/* Imported by src/styles/globals.css. */",
        block("@theme inline", lines),
        ...monoUtilities,
        "",
    ].join("\n")
}

function tokensJson(): string {
    const colorTokens = Object.fromEntries(
        colors.map((c) => [
            c.name,
            {
                $type: "color",
                $value: c.value.light,
                $description: c.usage,
                $extensions: {"com.agenta.modes": {dark: c.value.dark}},
            },
        ]),
    )
    const dims = (list: ThemeVariable[]) =>
        Object.fromEntries(list.map((v) => [v.name, {$type: "dimension", $value: v.value, $description: v.usage}]))
    return `${JSON.stringify(
        {
            color: colorTokens,
            typography: Object.fromEntries(
                textStyles.map((t) => [
                    t.name,
                    {
                        $type: "typography",
                        $value: {
                            fontFamily: fontFamilies[t.family],
                            fontSize: t.fontSize,
                            lineHeight: t.lineHeight,
                            fontWeight: t.fontWeight,
                            letterSpacing: t.letterSpacing ?? "0",
                        },
                        $description: t.usage,
                    },
                ]),
            ),
            spacing: dims(spacing),
            radius: dims(radius),
            size: dims(sizes),
            shadow: Object.fromEntries(
                shadows.map((s) => [
                    s.name,
                    {$type: "shadow", $value: s.value.light, $description: s.usage, $extensions: {"com.agenta.modes": {dark: s.value.dark}}},
                ]),
            ),
            duration: Object.fromEntries(durations.map((d) => [d.name, {$type: "duration", $value: d.value, $description: d.usage}])),
        },
        null,
        2,
    )}\n`
}

function designTables(): Record<string, string> {
    const row = (cells: string[]) => `| ${cells.join(" | ")} |`
    const colorRows = colors.map((c) =>
        row([
            `\`${c.name}\``,
            `\`${c.value.light}\``,
            `\`${c.value.dark}\``,
            c.usage.replace(/\\/g, "\\\\").replace(/\|/g, "\\|"),
        ]),
    )
    const textRows = textStyles.map((t) =>
        row([`\`${t.name}\``, `${t.fontSize} / ${t.lineHeight}`, String(t.fontWeight), t.letterSpacing ?? "0", t.usage]),
    )
    const scaleRows = [...spacing, ...radius, ...sizes, ...durations, ...easings, ...breakpoints, ...zIndex].map((v) =>
        row([`\`${v.name}\``, `\`${v.value}\``, v.usage]),
    )
    return {
        colors: [row(["Variable", "Light", "Dark", "Use"]), row(["---", "---", "---", "---"]), ...colorRows].join("\n"),
        "text-styles": [row(["Style", "Size / line", "Weight", "Tracking", "Use"]), row(["---", "---", "---", "---", "---"]), ...textRows].join("\n"),
        scales: [row(["Variable", "Value", "Use"]), row(["---", "---", "---"]), ...scaleRows].join("\n"),
    }
}

interface DesignRule {
    id: string
    rule: string
    why: string
    avoid: string
    do: string
    checkedBy: ("ratchet" | "lint" | "review")[]
}

/** The principles and rule tables of DESIGN.md, so the guide shows the same words. */
function rulesJson(markdown: string): string {
    const cells = (line: string) => line.slice(1, -1).split(" | ").map((c) => c.trim())
    const principles = [...markdown.matchAll(/^\d+\. \*\*(.+?)\*\* (.+)$/gm)].map((m) => ({title: m[1].replace(/[.:]$/, ""), body: m[2]}))
    const rulesPart = markdown.slice(markdown.indexOf("\n## Rules\n"), markdown.indexOf("\n## Working with the system"))
    const checks = (label: string) =>
        new Set([...(rulesPart.match(new RegExp(`^- ${label}[^\n]*`, "m"))?.[0] ?? "").matchAll(/`([A-Z]+-\d+)`/g)].map((m) => m[1]))
    const ratchet = checks("Ratchet")
    const lint = checks("ESLint")
    const groups: {prefix: string; title: string; rules: DesignRule[]}[] = []
    for (const section of rulesPart.split(/^### /m).slice(1)) {
        const [title, ...lines] = section.split("\n")
        const rows = lines.filter((l) => /^\| `[A-Z]+-\d+` \|/.test(l))
        if (!rows.length) continue
        const rules = rows.map((l) => {
            const [id, rule, why, avoid, doInstead] = cells(l)
            const bare = id.replace(/`/g, "")
            const checkedBy: DesignRule["checkedBy"] = []
            if (ratchet.has(bare)) checkedBy.push("ratchet")
            if (lint.has(bare)) checkedBy.push("lint")
            checkedBy.push("review")
            return {id: bare, rule, why, avoid, do: doInstead, checkedBy}
        })
        const prefixes = new Set(rules.map((r) => r.id.split("-")[0]))
        if (prefixes.size !== 1) throw new Error(`DESIGN.md: the "${title}" table mixes rule prefixes: ${[...prefixes].join(", ")}`)
        rules.forEach((r, i) => {
            const n = String(i + 1).padStart(2, "0")
            if (!r.id.endsWith(`-${n}`)) throw new Error(`DESIGN.md: ${r.id} is out of order in "${title}"; expected ${[...prefixes][0]}-${n}`)
        })
        groups.push({prefix: [...prefixes][0], title: title.trim(), rules})
    }
    const seen = new Set<string>()
    for (const g of groups) {
        if (seen.has(g.prefix)) throw new Error(`DESIGN.md: the prefix ${g.prefix} is used by two tables`)
        seen.add(g.prefix)
    }
    return JSON.stringify({principles, groups}, null, 4) + "\n"
}

function withTables(markdown: string): string {
    let out = markdown
    for (const [name, table] of Object.entries(designTables())) {
        const start = `<!-- generated:${name}:start -->`
        const end = `<!-- generated:${name}:end -->`
        const re = new RegExp(`${start}[\\s\\S]*?${end}`)
        if (!re.test(out)) throw new Error(`DESIGN.md is missing the ${start} … ${end} markers`)
        out = out.replace(re, `${start}\n\n${table}\n\n${end}`)
    }
    return out
}

const outputs: [string, string][] = [
    [resolve(DESIGN, "theme.css"), themeCss()],
    [resolve(DESIGN, "theme.tailwind.css"), tailwindCss()],
    [resolve(DESIGN, "tokens.json"), tokensJson()],
]
if (existsSync(DESIGN_MD)) {
    const markdown = readFileSync(DESIGN_MD, "utf8")
    outputs.push([DESIGN_MD, withTables(markdown)], [resolve(DESIGN, "rules.json"), rulesJson(markdown)])
}

const check = process.argv.includes("--check")
let stale = 0
for (const [file, content] of outputs) {
    const current = existsSync(file) ? readFileSync(file, "utf8") : ""
    if (current === content) continue
    if (check) {
        stale++
        console.error(`out of date: ${file}`)
    } else {
        writeFileSync(file, content)
        console.log(`wrote ${file}`)
    }
}
if (check && stale) {
    console.error("Run `pnpm generate:theme` in web/mobile and commit the result.")
    process.exit(1)
}
