/**
 * generate-phosphor-catalog.ts — emit the agent-icon catalog from @phosphor-icons/core.
 *
 * The agent icon picker lets a user choose any Phosphor icon. Importing the React barrel to
 * do that would defeat tree-shaking (4.8 MB into the entry chunk), and a per-icon dynamic
 * import would emit ~1512 chunks. So we ship the raw `regular`-weight path data instead: one
 * generated module, lazily imported by the picker only.
 *
 * Only the `regular` weight is read, which is what enforces the outline-only rule — no other
 * weight exists in the output.
 *
 * NOT committed. `prepare` runs it on every `pnpm install`, the way @agentaai/api-client builds
 * its dist/ — a 12k-line generated file in every diff is not worth the convenience of tracking it.
 *
 * Run: pnpm --filter @agenta/ui generate:icons   (or just `pnpm install`)
 */
import {existsSync, readdirSync, readFileSync, mkdirSync, writeFileSync} from "fs"
import {createRequire} from "module"
import {dirname, resolve as pathResolve} from "path"
import {fileURLToPath} from "url"

import {icons} from "@phosphor-icons/core"

const HERE = dirname(fileURLToPath(import.meta.url)) // packages/agenta-ui/scripts
const PKG = pathResolve(HERE, "..") // packages/agenta-ui
// The package does not export ./package.json, so locate it via its main entry: dist/ and assets/
// are siblings.
const ASSETS = pathResolve(
    createRequire(import.meta.url).resolve("@phosphor-icons/core"),
    "../../assets/regular",
)
const OUT = pathResolve(PKG, "src/agent-icon/catalog.generated.ts")

/** Everything between the outer `<svg …>` and `</svg>` — the shapes, without the wrapper. */
const innerMarkup = (svg: string): string =>
    svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "")

if (!existsSync(ASSETS)) {
    throw new Error(
        `@phosphor-icons/core assets not found at ${ASSETS}. Run \`pnpm install\` in web/ first.`,
    )
}

const available = new Set(
    readdirSync(ASSETS)
        .filter((file) => file.endsWith(".svg"))
        .map((file) => file.slice(0, -".svg".length)),
)

const missing: string[] = []
const entries = icons
    .filter((icon) => {
        if (available.has(icon.name)) return true
        missing.push(icon.name)
        return false
    })
    .map((icon) => ({
        name: icon.name,
        tags: icon.tags ?? [],
        categories: (icon.categories ?? []) as string[],
        path: innerMarkup(readFileSync(pathResolve(ASSETS, `${icon.name}.svg`), "utf8")).trim(),
    }))

const body = entries
    .map(
        (entry) =>
            `    {\n` +
            `        name: ${JSON.stringify(entry.name)},\n` +
            `        tags: ${JSON.stringify(entry.tags)},\n` +
            `        categories: ${JSON.stringify(entry.categories)},\n` +
            `        path: ${JSON.stringify(entry.path)},\n` +
            `    },`,
    )
    .join("\n")

const file = `/**
 * GENERATED by scripts/generate-phosphor-catalog.ts from @phosphor-icons/core.
 * Do not hand-edit — run \`pnpm generate:phosphor-catalog\` from web/ instead.
 *
 * \`regular\` weight only: the agent icon is outline-only by rule, and generating one weight is
 * what enforces it. \`path\` is the inner markup of the icon's 0 0 256 256 viewBox.
 */

export interface PhosphorCatalogEntry {
    /** Kebab-case Phosphor name, e.g. "git-pull-request". This is what we persist. */
    name: string
    tags: string[]
    categories: string[]
    /** Inner SVG markup, drawn with \`fill="currentColor"\`. */
    path: string
}

export const phosphorCatalog: PhosphorCatalogEntry[] = [
${body}
]
`

mkdirSync(dirname(OUT), {recursive: true})
writeFileSync(OUT, file, "utf8")

const kb = Math.round(Buffer.byteLength(file) / 1024)
console.log(`wrote ${entries.length} icons (${kb} KB) → ${OUT.replace(PKG + "/", "")}`)
if (missing.length)
    console.warn(`skipped ${missing.length} with no regular asset: ${missing.join(", ")}`)
