// Writes theme.css, theme.tailwind.css and tokens.json from theme.config.ts.
// Also checks web/DESIGN.md against its own Glossary and rules.json for shape; it writes neither.
import {existsSync, readFileSync, writeFileSync} from "fs"
import {dirname, resolve} from "path"
import {fileURLToPath} from "url"

import {
    breakpoints,
    colorAliases,
    colors,
    durations,
    easings,
    fontFamilies,
    radius,
    shadows,
    sizes,
    spacing,
    textStyles,
    zIndex,
    type ThemeMode,
    type ThemeVariable,
} from "../src/design/theme.config"

const HERE = dirname(fileURLToPath(import.meta.url))
const DESIGN = resolve(HERE, "../src/design")
const DESIGN_MD = resolve(HERE, "../../../DESIGN.md")

// Light on :root; dark on the `.dark` class that _document.tsx sets on <html> before paint.
const SCOPE = ":root"
const DARK_SCOPE = ".dark"

const HEADER =
    "/* GENERATED by scripts/generate-theme.ts from src/design/theme.config.ts. Do not edit. */"
// A compact window (below breakpoint-sm) steps the default and large controls down one size.
const COMPACT_SIZES = ["control-md", "control-lg"]

const cssName = (name: string) => `--${name.replace(/\\/g, "\\\\").replace(/\./g, "\\.")}`

function block(selector: string, lines: string[]) {
    return `${selector} {\n${lines.map((l) => `    ${l}`).join("\n")}\n}`
}

function themeCss(): string {
    const plain = (list: ThemeVariable[]) => list.map((v) => `${cssName(v.name)}: ${v.value};`)
    const light = [
        ...colors.map((c) => `--${c.name}: ${c.value.light};`),
        ...shadows.map((s) => `--${s.name}: ${s.value.light};`),
        ...Object.entries(fontFamilies).map(([k, v]) => `--font-${k}: ${v};`),
        ...textStyles.flatMap((t) => [
            `--${t.name}: ${t.fontSize};`,
            `--${t.name}--line-height: ${t.lineHeight};`,
            `--${t.name}--font-weight: ${t.fontWeight};`,
            `--${t.name}--letter-spacing: ${t.letterSpacing ?? "0"};`,
        ]),
        ...plain(spacing),
        ...plain(radius),
        ...plain(sizes),
        ...plain(durations),
        ...plain(easings),
        ...plain(breakpoints),
        ...plain(zIndex),
    ]
    const dark = [
        ...colors.map((c) => `--${c.name}: ${c.value.dark};`),
        ...shadows.map((s) => `--${s.name}: ${s.value.dark};`),
        "color-scheme: dark;",
    ]
    const compact = COMPACT_SIZES.map((n) => `--${n}: var(--${n}-compact);`)
    return [
        HEADER,
        block(SCOPE, light),
        block(DARK_SCOPE, dark),
        `/* Small screens get smaller controls: the default and large sizes step down one size. Touch never grows a control's look. */\n@media (max-width: 639px) {\n${block(`    ${SCOPE}`, compact).replace(/\n/g, "\n    ")}\n}`,
        "",
    ].join("\n\n")
}

// No `--<namespace>-*: initial` resets: stock keys (text-xs, md:, shadow-sm, gray-500, ...) are still
// in use. Add the resets once design:ratchet shows those uses at zero.
function tailwindCss(): string {
    const lines = [
        ...colors.map((c) => `--color-${c.name}: var(--${c.name});`),
        ...Object.entries(colorAliases).map(([alias, to]) => `--color-${alias}: var(--${to});`),
        ...Object.keys(fontFamilies).map((k) => `--font-${k}: var(--font-${k});`),
        ...textStyles.flatMap((t) => [
            `--text-${t.name.replace(/^text-/, "")}: var(--${t.name});`,
            `--text-${t.name.replace(/^text-/, "")}--line-height: var(--${t.name}--line-height);`,
            `--text-${t.name.replace(/^text-/, "")}--font-weight: var(--${t.name}--font-weight);`,
            `--text-${t.name.replace(/^text-/, "")}--letter-spacing: var(--${t.name}--letter-spacing);`,
        ]),
        "--spacing: 4px;",
        ...radius.map((r) => `--${r.name}: var(--${r.name});`),
        ...shadows.map((s) => `--${s.name}: var(--${s.name});`),
        ...breakpoints.map((b) => `--${b.name}: ${b.value};`),
        // max-w-content-sm / -md / -lg (LAYOUT-02).
        ...sizes
            .filter((s) => s.name.startsWith("content-"))
            .map((s) => `--container-${s.name}: var(--${s.name});`),
        // w-popover-sm / -md / -lg and h-row-dense / -single / -double.
        ...sizes
            .filter((s) => s.name.startsWith("popover-"))
            .map((s) => `--container-${s.name}: var(--${s.name});`),
        ...sizes
            .filter((s) => s.name.startsWith("row-"))
            .map((s) => `--spacing-${s.name}: var(--${s.name});`),
        // The page frame: h-header, px-page-margin, w-panel-side.
        "--spacing-header: var(--header-h);",
        "--spacing-page-margin: var(--page-margin);",
        "--container-panel-side: var(--panel-side);",
        ...easings.map((e) => `--${e.name}: var(--${e.name});`),
        // A bare `transition-colors` moves on the theme's hover timing, not Tailwind's 150ms
        // default (MOTION-01: no duration or easing written in a component).
        "--default-transition-duration: var(--duration-fast);",
        "--default-transition-timing-function: var(--ease-out);",
    ]
    // Tailwind's --text-* theme keys cannot carry a font family, so mono styles add it here.
    const monoUtilities = textStyles
        .filter((t) => t.family === "mono")
        .map((t) => block(`@utility ${t.name}`, ["font-family: var(--font-mono);"]))
    return [
        HEADER,
        "/* Imported by src/styles/globals.css. */",
        block("@theme inline", lines),
        ...monoUtilities,
        "",
    ].join("\n")
}

function tokensJson(): string {
    const colorTokens = Object.fromEntries(
        colors.map((c) => [
            c.name,
            {
                $type: "color",
                $value: c.value.light,
                $description: c.usage,
                $extensions: {"com.agenta.modes": {dark: c.value.dark}},
            },
        ]),
    )
    const dims = (list: ThemeVariable[]) =>
        Object.fromEntries(
            list.map((v) => [v.name, {$type: "dimension", $value: v.value, $description: v.usage}]),
        )
    return `${JSON.stringify(
        {
            color: colorTokens,
            typography: Object.fromEntries(
                textStyles.map((t) => [
                    t.name,
                    {
                        $type: "typography",
                        $value: {
                            fontFamily: fontFamilies[t.family],
                            fontSize: t.fontSize,
                            lineHeight: t.lineHeight,
                            fontWeight: t.fontWeight,
                            letterSpacing: t.letterSpacing ?? "0",
                        },
                        $description: t.usage,
                    },
                ]),
            ),
            spacing: dims(spacing),
            radius: dims(radius),
            size: dims(sizes),
            shadow: Object.fromEntries(
                shadows.map((s) => [
                    s.name,
                    {
                        $type: "shadow",
                        $value: s.value.light,
                        $description: s.usage,
                        $extensions: {"com.agenta.modes": {dark: s.value.dark}},
                    },
                ]),
            ),
            duration: Object.fromEntries(
                durations.map((d) => [
                    d.name,
                    {$type: "duration", $value: d.value, $description: d.usage},
                ]),
            ),
        },
        null,
        2,
    )}\n`
}

interface DesignRule {
    id: string
    rule: string
    why: string
    avoid: string
    do: string
    checkedBy: ("ratchet" | "lint" | "review")[]
}

/** rules.json is written by hand: one prefix per group, IDs in order, every field filled. */
function checkRules(json: string): void {
    const {groups, terms} = JSON.parse(json) as {
        groups: {prefix: string; title: string; rules: DesignRule[]}[]
        terms: {term: string; icon: string}[]
    }
    const seen = new Set<string>()
    for (const g of groups) {
        if (seen.has(g.prefix))
            throw new Error(`rules.json: the prefix ${g.prefix} is used by two groups`)
        seen.add(g.prefix)
        g.rules.forEach((r, i) => {
            const id = `${g.prefix}-${String(i + 1).padStart(2, "0")}`
            if (r.id !== id)
                throw new Error(
                    `rules.json: ${r.id} is out of order in "${g.title}"; expected ${id}`,
                )
            for (const k of ["rule", "why", "avoid", "do"] as const)
                if (!r[k]) throw new Error(`rules.json: ${r.id} has no "${k}"`)
        })
    }
    if (!terms.length) throw new Error("rules.json has no icon terms")
}

/** DESIGN.md follows its own Glossary: no word from the "Do not say" column outside that table. */
function checkGlossary(markdown: string): void {
    const start = markdown.indexOf("\n## Glossary\n")
    const end = markdown.indexOf("\n## Principles\n")
    if (start < 0 || end < 0)
        throw new Error("DESIGN.md is missing the Glossary or the Principles section")
    const banned = markdown
        .slice(start, end)
        .split("\n")
        .filter((l) => l.startsWith("| ") && !/^\| (Word|---) /.test(l))
        .flatMap((l) => (l.slice(1, -1).split(" | ")[2] ?? "").replace(/\(.*?\)/g, "").split(","))
        .map((w) => w.trim())
        .filter(Boolean)
    const hits: string[] = []
    const body = markdown.slice(0, start) + markdown.slice(end)
    body.split("\n").forEach((line) => {
        const text = line.replace(/`[^`]*`/g, "")
        for (const word of banned) {
            if (new RegExp(`\\b${word}s?\\b`, "i").test(text))
                hits.push(`"${word}" in: ${line.trim().slice(0, 90)}`)
        }
    })
    if (hits.length)
        throw new Error(`DESIGN.md uses words its Glossary bans:\n  ${hits.join("\n  ")}`)
}

const outputs: [string, string][] = [
    [resolve(DESIGN, "theme.css"), themeCss()],
    [resolve(DESIGN, "theme.tailwind.css"), tailwindCss()],
    [resolve(DESIGN, "tokens.json"), tokensJson()],
]
checkGlossary(readFileSync(DESIGN_MD, "utf8"))
checkRules(readFileSync(resolve(DESIGN, "rules.json"), "utf8"))

const check = process.argv.includes("--check")
let stale = 0
for (const [file, content] of outputs) {
    const current = existsSync(file) ? readFileSync(file, "utf8") : ""
    if (current === content) continue
    if (check) {
        stale++
        console.error(`out of date: ${file}`)
    } else {
        writeFileSync(file, content)
        console.log(`wrote ${file}`)
    }
}
if (check && stale) {
    console.error("Run `pnpm --filter @agenta/ui generate:theme` in web and commit the result.")
    process.exit(1)
}
