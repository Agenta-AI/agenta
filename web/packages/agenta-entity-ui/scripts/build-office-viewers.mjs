// Bundles each office viewer (renderer + frame runtime) into a self-contained script string module.
// `--check` fails when a checked-in module no longer matches its source.
import {readFile, writeFile} from "node:fs/promises"
import {dirname, join} from "node:path"
import {fileURLToPath} from "node:url"

import {build} from "esbuild"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const dir = join(root, "src/drive/officeViewer")
const check = process.argv.includes("--check")

const viewers = [
    {entry: "frame/docx.ts", out: "generated/docxViewer.ts", name: "DOCX_VIEWER_SCRIPT"},
    {entry: "frame/pptx.ts", out: "generated/pptxViewer.ts", name: "PPTX_VIEWER_SCRIPT"},
]

const stale = []
for (const {entry, out, name} of viewers) {
    const result = await build({
        entryPoints: [join(dir, entry)],
        bundle: true,
        format: "iife",
        platform: "browser",
        target: "es2020",
        minify: true,
        legalComments: "none",
        write: false,
        define: {"process.env.NODE_ENV": '"production"'},
    })
    const code = result.outputFiles[0].text
    const module =
        "// Generated by scripts/build-office-viewers.mjs. Do not edit.\n" +
        "/* eslint-disable */\n" +
        `export const ${name} = ${JSON.stringify(code)}\n`
    if (check) {
        const current = await readFile(join(dir, out), "utf8").catch(() => "")
        if (current !== module) stale.push(out)
        continue
    }
    await writeFile(join(dir, out), module)
    console.log(`${out}: ${(code.length / 1024).toFixed(0)} KB`)
}

if (stale.length) {
    console.error(
        `Stale: ${stale.join(", ")}. Run pnpm --filter @agenta/entity-ui build:office-viewers and commit the result.`,
    )
    process.exit(1)
}
