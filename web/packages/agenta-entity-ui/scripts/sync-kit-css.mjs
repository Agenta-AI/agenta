/**
 * Copies src/drive/htmlApp/kit/agenta-app.css into kitCss.ts as a string constant. The package
 * has no raw-CSS loader (Next treats a package .css import as global CSS), so the TS twin is
 * what ships; htmlApp.kit.test.ts fails when the two drift. Run: pnpm kit:sync
 */
import {readFileSync, writeFileSync} from "node:fs"
import {dirname, join} from "node:path"
import {fileURLToPath} from "node:url"

const kitDir = join(dirname(fileURLToPath(import.meta.url)), "../src/drive/htmlApp/kit")
const css = readFileSync(join(kitDir, "agenta-app.css"), "utf8")

if (/[`\\]|\$\{/.test(css)) {
    throw new Error("agenta-app.css must not contain backticks, backslashes or ${")
}

const out = `// GENERATED by scripts/sync-kit-css.mjs from agenta-app.css — do not edit by hand.
/** The kit stylesheet as a string, ready for a <style> tag in the app document. */
export const KIT_CSS = \`${css}\`
`
writeFileSync(join(kitDir, "kitCss.ts"), out)
console.log(`kitCss.ts synced (${Buffer.byteLength(css)} bytes)`)
