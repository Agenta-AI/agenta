// Pure content-negotiation helpers for the edge worker (worker/index.ts).
//
// Kept free of Workers globals so it unit-tests under plain vitest — the worker
// runtime surface we touch is `env.ASSETS.fetch`, and that lives next door.

/** One parsed entry of an Accept header. */
export type AcceptEntry = {
  type: string;
  q: number;
  specificity: number;
  /** Where the client wrote it, which survives the sort below. */
  position: number;
};

/** A representation of a page this site can actually serve. */
export type Representation = "html" | "markdown" | "json";

/**
 * The `/*` policy from public/_headers. Cloudflare does NOT apply _headers to
 * responses generated by Worker code, so every response this worker builds (or
 * re-wraps) has to carry the policy itself. Keep in sync with public/_headers.
 */
export const HEADERS: Record<string, string> = {
  "Cache-Control": "public, max-age=60, stale-while-revalidate=3600",
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "SAMEORIGIN",
  "Referrer-Policy": "strict-origin-when-cross-origin",
};

/** Media types we can actually serve, by representation. */
const HTML_TYPES = new Set([
  "text/html",
  "application/xhtml+xml",
  "application/xml",
]);
const MARKDOWN_TYPES = new Set(["text/markdown", "text/x-markdown"]);

/**
 * Parse an Accept header into entries ordered by preference: q descending,
 * then specificity (exact type, then subtype wildcard, then full wildcard).
 * `Array.sort` is stable, so equally ranked entries keep their source order.
 * RFC 9110 §12.5.1.
 */
export function parseAccept(header: string | null | undefined): AcceptEntry[] {
  if (!header) return [];

  const entries: AcceptEntry[] = [];
  for (const [position, part] of header.split(",").entries()) {
    const [rawType, ...params] = part.split(";");
    const type = rawType.trim().toLowerCase();
    if (!type) continue;

    let q = 1;
    for (const param of params) {
      const [key, value] = param.split("=");
      if (key?.trim().toLowerCase() === "q") {
        const parsed = Number.parseFloat(value ?? "");
        // A malformed q is treated as 1 (a missing q), never as a rejection.
        if (Number.isFinite(parsed)) q = Math.min(Math.max(parsed, 0), 1);
      }
    }

    entries.push({
      type,
      q,
      specificity: type === "*/*" ? 0 : type.endsWith("/*") ? 1 : 2,
      position,
    });
  }

  return entries.sort((a, b) => b.q - a.q || b.specificity - a.specificity);
}

const ALL: Representation[] = ["html", "markdown", "json"];

/** The media types each representation answers to. */
const MEDIA_TYPES: Record<Representation, string[]> = {
  // A client asking only for XHTML or XML still gets the HTML page: those
  // clients (unfurlers, XHTML-era agents) read it fine, and a 406 would be a
  // worse answer than a slightly broader content type.
  html: ["text/html", "application/xhtml+xml", "application/xml"],
  markdown: ["text/markdown", "text/x-markdown"],
  json: ["application/json"],
};

/**
 * The quality this header assigns a representation, resolved against the most
 * specific range that matches it (RFC 9110 §12.5.1).
 *
 * Specificity matters for exclusions: in `text/*;q=1, text/html;q=0` the exact
 * range wins, so HTML is rejected even though the wildcard accepted it.
 */
function qualityFor(
  entries: AcceptEntry[],
  representation: Representation,
): { q: number; position: number } {
  let bestSpecificity = -1;
  let bestQ = 0;
  let bestPosition = 0;

  MEDIA_TYPES[representation].forEach((mediaType) => {
    const [type] = mediaType.split("/");
    entries.forEach((entry) => {
      const specificity =
        entry.type === mediaType
          ? 2
          : entry.type === `${type}/*`
            ? 1
            : entry.type === "*/*"
              ? 0
              : -1;
      if (specificity <= bestSpecificity) return;
      bestSpecificity = specificity;
      bestQ = entry.q;
      // The client's own ordering, not this entry's rank after sorting.
      bestPosition = entry.position;
    });
  });

  return bestSpecificity < 0
    ? { q: 0, position: 0 }
    : { q: bestQ, position: bestPosition };
}

/**
 * Every representation the client will accept, best first.
 *
 * A ranked list rather than a single winner, because the best match is not
 * always one we have: a client asking for JSON and markdown should get the
 * markdown twin, not HTML it did not ask for. An empty list means nothing we
 * serve was accepted, which is a 406.
 */
export function acceptedRepresentations(
  header: string | null | undefined,
): Representation[] {
  const entries = parseAccept(header);
  // No header at all (or nothing parseable): the client takes anything.
  if (entries.length === 0) return ALL;

  return ALL.map((representation) => ({
    representation,
    ...qualityFor(entries, representation),
  }))
    .filter((candidate) => candidate.q > 0)
    // Highest quality first; between equals, whichever the client named first.
    .sort((a, b) => b.q - a.q || a.position - b.position)
    .map((candidate) => candidate.representation);
}

/**
 * Markdown twin of an HTML route: `/pricing` → `/pricing.md`, `/` → `/index.md`.
 *
 * Returns null for anything that already names a file (assets, /llms.txt,
 * /openapi.json, and the twins themselves) — those are served verbatim and
 * never negotiated. A trailing slash is stripped first: the live sitemap
 * advertises the slash form, and a Cloudflare Transform Rule may re-add it for
 * /authors/<slug>/.
 */
export function mdPath(pathname: string): string | null {
  const lastSegment = pathname.split("/").pop() ?? "";
  if (lastSegment.includes(".")) return null;

  const clean = pathname.replace(/\/+$/, "");
  return clean === "" ? "/index.md" : `${clean}.md`;
}

const SITE = "https://agenta.ai";

/** The machine-readable entry points an agent should try after a dead end. */
const RECOVERY = {
  sitemap: `${SITE}/sitemap-index.xml`,
  llms_txt: `${SITE}/llms.txt`,
  openapi: `${SITE}/openapi.json`,
  docs: "https://docs.agenta.ai",
};

/** Short markdown body for a 404, pointing agents at the machine-readable map. */
export function notFoundMarkdown(pathname: string): string {
  return `# 404 — page not found

\`${pathname}\` does not exist on agenta.ai.

Agenta is the open-source workspace for your agents.

## Where to look next

- [Homepage](${SITE}/)
- [Blog](${SITE}/blog)
- [Pricing](${SITE}/pricing)
- [Documentation](${RECOVERY.docs})

## Machine-readable

- [Sitemap](${RECOVERY.sitemap})
- [llms.txt](${RECOVERY.llms_txt})
- [OpenAPI specification](${RECOVERY.openapi})

Every page also serves markdown via \`Accept: text/markdown\`.
`;
}

/**
 * Structured error body: a code, a message, hints an agent can act on, and the
 * entry points above so a lost client always has somewhere to go.
 */
export function errorJson(error: {
  status: number;
  code: string;
  message: string;
  path: string;
  hints: string[];
}): string {
  return JSON.stringify({ error: { ...error, ...RECOVERY } }, null, 2);
}

/** Body for a 406: say plainly what representations exist. */
export function notAcceptableJson(path: string): string {
  return errorJson({
    status: 406,
    code: "not_acceptable",
    message:
      "None of the media types in the Accept header can be served for this resource.",
    path,
    hints: [
      "Request text/html for the rendered page.",
      "Request text/markdown for the plain-text representation.",
      "Request application/json for structured errors.",
    ],
  });
}
