#!/usr/bin/env node
// Generates src/components/hero-app/ph.jsx: only the Phosphor glyphs (and weights) the hero
// mockup uses. Importing "@phosphor-icons/react" directly ships all six weights of every icon,
// about 80 KB gzip for the mockup. Run after you add an icon import from "./ph.jsx":
//   node scripts/gen-hero-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/components/hero-app");
const require = createRequire(join(root, "package.json"));
const phosphor = dirname(require.resolve("@phosphor-icons/react/package.json"));

const names = new Map(); // name -> Set(weights)
for (const file of readdirSync(dir).filter(
  (f) => f.endsWith(".jsx") && f !== "ph.jsx",
)) {
  const src = readFileSync(join(dir, file), "utf8");
  for (const m of src.matchAll(
    /import\s*\{([^}]*)\}\s*from\s*"\.\/ph\.jsx"/g,
  )) {
    for (const part of m[1].split(",")) {
      const [name, alias] = part.trim().split(/\s+as\s+/);
      if (!name) continue;
      const local = alias ?? name;
      const weights = names.get(name) ?? new Set(["regular"]);
      for (const w of src.matchAll(
        new RegExp(`<${local}\\b[^>]*?weight="(\\w+)"`, "g"),
      ))
        weights.add(w[1]);
      names.set(name, weights);
    }
  }
}

const serialize = (el) => {
  const { children, ...props } = el.props ?? {};
  const kids =
    children == null ? [] : Array.isArray(children) ? children : [children];
  if (typeof el.type === "symbol" || el.type?.toString?.().includes("Fragment"))
    return kids.map(serialize).flat();
  return [[el.type, props]];
};

const out = [];
for (const [name, weights] of [...names].sort()) {
  const mod = await import(
    pathToFileURL(join(phosphor, "dist/defs", `${name}.es.js`)).href
  );
  const map = mod.default;
  const entry = {};
  for (const w of weights) entry[w] = serialize(map.get(w));
  out.push(`export const ${name} = icon(${JSON.stringify(entry)});`);
}

writeFileSync(
  join(dir, "ph.jsx"),
  `// GENERATED by scripts/gen-hero-icons.mjs from @phosphor-icons/react. Do not edit.
// The same API as the Phosphor components (size, weight, mirrored, className), with only the
// weights the mockup uses.
const icon = (weights) => {
  const Icon = ({ size = 16, weight = "regular", mirrored, className, style }) => (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 256 256"
      fill="currentColor"
      aria-hidden="true"
      className={className}
      style={style}
      transform={mirrored ? "scale(-1, 1)" : undefined}
    >
      {(weights[weight] ?? weights.regular).map(([Tag, props], i) => <Tag key={i} {...props} />)}
    </svg>
  );
  return Icon;
};

${out.join("\n")}
`,
);
console.log(`ph.jsx: ${names.size} icons`);
